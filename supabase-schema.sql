-- Run in Supabase SQL Editor.
create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 order_code text unique not null,
 tracking_token text not null,
 customer_name text not null,
 branch text not null,
 items jsonb not null,
 total numeric(10,2) not null,
 payment_screenshot_path text not null,
 order_status text not null default 'pending' check(order_status in ('pending','confirmed','delivered')),
 created_at timestamptz not null default now()
);
alter table public.orders enable row level security;

-- Anonymous customers can submit orders only.
create policy "public create orders" on public.orders for insert to anon,authenticated
with check(order_status='pending');

-- Only authenticated admin can see/change orders.
create policy "admin read orders" on public.orders for select to authenticated using(true);
create policy "admin update orders" on public.orders for update to authenticated using(true)
with check(order_status in ('pending','confirmed','delivered'));
grant insert on public.orders to anon,authenticated;
grant select,update on public.orders to authenticated;

-- Private bucket for payment proof screenshots.
insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values('payment-screenshots','payment-screenshots',false,5242880,array['image/jpeg','image/png','image/webp'])
on conflict(id) do nothing;
create policy "customers upload payment proof" on storage.objects for insert to anon,authenticated
with check(bucket_id='payment-screenshots');
create policy "admins view payment proof" on storage.objects for select to authenticated
using(bucket_id='payment-screenshots');

-- Safe customer tracking: returns only one order status if code + secret token match.
create or replace function public.get_order_status(p_order_code text,p_tracking_token text)
returns table(order_status text)
language sql security definer set search_path=public
as $$
 select o.order_status from public.orders o
 where o.order_code=p_order_code and o.tracking_token=p_tracking_token
 limit 1;
$$;
revoke all on function public.get_order_status(text,text) from public;
grant execute on function public.get_order_status(text,text) to anon,authenticated;

